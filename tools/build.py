# ── neovim palette table ────────────────────────────────────────────────────
def nvim_palettes():
    keys = ["bg", "bg_dark", "surface", "surface_high", "fg", "fg_heading", "fg_muted", "comment",
            "selection", "blue", "cyan", "purple", "green", "yellow", "red", "orange", "accent",
            "on_accent", "search_bg", "search_fg", "search_hl_bg"]
    out = ["-- Generated by tools/build.py from tools/palettes.py. Do not edit by hand.", "return {"]
    for n, p in THEMES.items():
        out.append(f'  ["{n}"] = {{')
        out.append(f'    kind = "{p["kind"]}",')
        for k in keys:
            out.append(f'    {k} = "{p[k]}",')
        out.append("  },")
    out.append("}")
    return "\n".join(out) + "\n"


# ── Windows Terminal ────────────────────────────────────────────────────────
def wt_scheme(n, p):
    a = p["ansi"]
    title = {"apple-classic-dark": "Apple Classic Pastel Dark",
             "powershell-light": "PowerShell Light",
             "sequoia-light": "Sequoia Light"}[n]
    return {
        "name": title,
        "background": p["bg"].upper(), "foreground": p["fg"].upper(),
        "cursorColor": a["cursor"].upper(),
        "selectionBackground": p["selection"].upper(),
        "black": a["black"].upper(), "red": a["red"].upper(), "green": a["green"].upper(),
        "yellow": a["yellow"].upper(), "blue": a["blue"].upper(), "purple": a["purple"].upper(),
        "cyan": a["cyan"].upper(), "white": a["white"].upper(),
        "brightBlack": a["brightBlack"].upper(), "brightRed": a["brightRed"].upper(),
        "brightGreen": a["brightGreen"].upper(), "brightYellow": a["brightYellow"].upper(),
        "brightBlue": a["brightBlue"].upper(), "brightPurple": a["brightPurple"].upper(),
        "brightCyan": a["brightCyan"].upper(), "brightWhite": a["brightWhite"].upper(),
    }


def main():
    if subprocess.call([sys.executable, os.path.join(HERE, "contrast.py")], stdout=subprocess.DEVNULL):
        subprocess.call([sys.executable, os.path.join(HERE, "contrast.py")])
        sys.exit("contrast check failed: fix tools/palettes.py")
    for n, p in THEMES.items():
        write(f"config/theme/themes/{n}/tmux.conf", tmux(n, p))
        write(f"config/theme/themes/{n}/starship-palette.toml", starship(n, p))
        write(f"config/theme/themes/{n}/fzf.zsh", fzf(n, p))
        write(f"config/leaf/themes/{n}.toml", leaf(n, p))
    write("config/nvim/lua/theme/palettes.lua", nvim_palettes())
    write("windows/terminal-schemes.json",
          json.dumps([wt_scheme(n, p) for n, p in THEMES.items()], indent=4) + "\n")
    if CHECK and STALE:
        sys.exit("out of date, run tools/build.py:\n  " + "\n  ".join(STALE))


if __name__ == "__main__":
    main()
